/**
 * Translate `key`, interpolating `{name}` placeholders from `vars`.
 * Returns the key itself when missing, so gaps are visible during review
 * rather than silently rendering as empty text.
 */
export function t(key, vars) {
  let s = STR[key];
  if (s === undefined) {
    if (typeof console !== 'undefined') console.warn('[i18n] liafuan laiha:', key);
    return key;
  }
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

/** Every key in the table — used by the translation-review dump. */
export function allKeys() {
  return Object.keys(STR);
}

/** Raw table access for the review tooling in docs/. */
export function rawStrings() {
  return { ...STR };
}
